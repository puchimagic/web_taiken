def main() -> None:
    data = json.loads(TARGET_PATH.read_text(encoding="utf-8"))
    for file_name, extra_list in EXTRA.items():
        if file_name not in data:
            raise SystemExit(f"{file_name} が spot_comments.json に存在しません")
        data[file_name] = data[file_name] + extra_list
    TARGET_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(EXTRA)}件のスポットに追加コメントをマージしました")


if __name__ == "__main__":
    main()
