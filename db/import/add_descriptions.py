def apply_descriptions(filename: str) -> None:
    path = ROOT / "db" / filename
    spots = json.loads(path.read_text(encoding="utf-8"))
    missing = []
    for spot in spots:
        file_name = spot["file"]
        if file_name in DESCRIPTIONS:
            spot["description"] = DESCRIPTIONS[file_name]
        else:
            missing.append(file_name)
    if missing:
        raise SystemExit(f"{filename}: description未定義のファイルがあります: {missing}")
    path.write_text(json.dumps(spots, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{filename}: {len(spots)}件にdescriptionを追加しました")


def main() -> None:
    apply_descriptions("seed_spots.json")
    apply_descriptions("seed_spots_new.json")


if __name__ == "__main__":
    main()
