def main() -> None:
    missing = []
    file_names = []
    for fname in ["seed_spots.json", "seed_spots_new.json"]:
        spots = json.loads((ROOT / "db" / fname).read_text(encoding="utf-8"))
        for s in spots:
            file_names.append(s["file"])
    for fn in file_names:
        if fn not in COMMENTS:
            missing.append(fn)
        elif not (3 <= len(COMMENTS[fn]) <= 6):
            raise SystemExit(f"{fn}: コメント件数が範囲外です（{len(COMMENTS[fn])}件）")
    if missing:
        raise SystemExit(f"コメント未定義のファイルがあります: {missing}")

    OUT_PATH.write_text(json.dumps(COMMENTS, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(COMMENTS)}スポット分のコメントを {OUT_PATH} に書き出しました")


if __name__ == "__main__":
    main()
